import { Ionicons } from '@expo/vector-icons';
import { useRoute } from '@react-navigation/native';
import { useEffect, useRef, useState } from 'react';
import {
  ActivityIndicator,
  KeyboardAvoidingView,
  Pressable,
  ScrollView,
  ScrollViewInstance,
  StyleSheet,
  Text,
  TextInput,
  View,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { api, errorMessage } from '../api';
import { colors } from '../theme';
import { s } from '../ui';

type Msg = { role: 'user' | 'assistant'; content: string; tools?: string[]; error?: boolean };

const SUGGESTIONS = [
  'When is my next appointment and how should I prepare?',
  'What do I owe right now?',
  'Summarize my latest lab results',
  'Who can see my medical info?',
];

const toolLabel: Record<string, string> = {
  get_profile: 'profile',
  list_appointments: 'appointments',
  list_bills: 'bills',
  list_lab_results: 'lab results',
  list_data_access: 'access list',
};

export default function AssistantScreen() {
  const route = useRoute<any>();
  const [messages, setMessages] = useState<Msg[]>([]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const scroll = useRef<ScrollViewInstance>(null);

  const send = async (text: string) => {
    const content = text.trim();
    if (!content || busy) return;
    const history = [...messages.filter((m) => !m.error), { role: 'user' as const, content }];
    setMessages((m) => [...m, { role: 'user', content }]);
    setInput('');
    setBusy(true);
    try {
      const res = await api<{ reply: string; tools_used: string[] }>('/me/assistant/chat', {
        body: { messages: history.map(({ role, content }) => ({ role, content })) },
      });
      setMessages((m) => [...m, { role: 'assistant', content: res.reply, tools: res.tools_used }]);
    } catch (e) {
      setMessages((m) => [...m, { role: 'assistant', content: errorMessage(e), error: true }]);
    } finally {
      setBusy(false);
    }
  };

  // Other screens deep-link here with a prompt ("Explain this result").
  useEffect(() => {
    if (route.params?.prompt) send(route.params.prompt);
  }, [route.params?.nonce]); // eslint-disable-line react-hooks/exhaustive-deps

  return (
    <SafeAreaView edges={['top']} style={{ flex: 1, backgroundColor: colors.bg }}>
      <View style={st.header}>
        <Ionicons name="sparkles" size={20} color={colors.primary} />
        <Text style={st.h1}>Assistant</Text>
        {messages.length > 0 && (
          <Pressable onPress={() => setMessages([])} hitSlop={10} style={{ marginLeft: 'auto' }}>
            <Text style={{ color: colors.primary, fontWeight: '600' }}>New chat</Text>
          </Pressable>
        )}
      </View>
      <KeyboardAvoidingView behavior="padding" style={{ flex: 1 }} keyboardVerticalOffset={80}>
        <ScrollView
          ref={scroll}
          contentContainerStyle={{ padding: 16, gap: 10 }}
          onContentSizeChange={() => scroll.current?.scrollToEnd({ animated: true })}
          keyboardShouldPersistTaps="handled"
        >
          {messages.length === 0 && (
            <View style={{ gap: 10 }}>
              <Text style={[s.body, { color: colors.muted, marginBottom: 6 }]}>
                Ask about your appointments, bills, results or who has access to your data. Answers are generated by
                Google’s Gemma model from your own 1Profile records. Card numbers are never shared with it.
              </Text>
              {SUGGESTIONS.map((q) => (
                <Pressable key={q} style={st.suggestion} onPress={() => send(q)}>
                  <Text style={{ color: colors.primary, fontWeight: '500' }}>{q}</Text>
                </Pressable>
              ))}
            </View>
          )}
          {messages.map((m, i) => (
            <View key={i} style={[st.bubble, m.role === 'user' ? st.user : st.bot, m.error && st.err]}>
              <Text style={[s.body, m.role === 'user' && { color: '#fff' }, m.error && { color: colors.danger }]}>
                {m.content.replace(/\*\*(.+?)\*\*/g, '$1')}
              </Text>
              {!!m.tools?.length && (
                <Text style={st.tools}>Checked: {[...new Set(m.tools.map((t) => toolLabel[t] ?? t))].join(', ')}</Text>
              )}
            </View>
          ))}
          {busy && (
            <View style={[st.bubble, st.bot, { flexDirection: 'row', gap: 8, alignItems: 'center' }]}>
              <ActivityIndicator size="small" color={colors.primary} />
              <Text style={s.muted}>Thinking…</Text>
            </View>
          )}
        </ScrollView>
        <View style={st.composer}>
          <TextInput
            style={st.input}
            placeholder="Ask anything about your 1Profile…"
            placeholderTextColor={colors.faint}
            value={input}
            onChangeText={setInput}
            onSubmitEditing={() => send(input)}
            returnKeyType="send"
            multiline
          />
          <Pressable onPress={() => send(input)} disabled={busy || !input.trim()} style={[st.send, (busy || !input.trim()) && { opacity: 0.4 }]}>
            <Ionicons name="arrow-up" size={20} color="#fff" />
          </Pressable>
        </View>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

const st = StyleSheet.create({
  header: { flexDirection: 'row', alignItems: 'center', gap: 8, paddingHorizontal: 16, paddingTop: 4, paddingBottom: 8 },
  h1: { fontSize: 28, fontWeight: '800', color: colors.text },
  suggestion: { backgroundColor: colors.card, borderWidth: 1, borderColor: colors.border, padding: 14, borderRadius: 14 },
  bubble: { maxWidth: '88%', padding: 12, borderRadius: 16 },
  user: { alignSelf: 'flex-end', backgroundColor: colors.primary, borderBottomRightRadius: 4 },
  bot: { alignSelf: 'flex-start', backgroundColor: colors.card, borderBottomLeftRadius: 4, borderWidth: 1, borderColor: colors.border },
  err: { backgroundColor: colors.dangerSoft, borderColor: colors.dangerSoft },
  tools: { fontSize: 11, color: colors.faint, marginTop: 6 },
  composer: { flexDirection: 'row', gap: 8, padding: 10, borderTopWidth: 1, borderTopColor: colors.border, backgroundColor: colors.card, alignItems: 'flex-end' },
  input: { flex: 1, maxHeight: 120, backgroundColor: colors.bg, borderRadius: 18, paddingHorizontal: 14, paddingTop: 10, paddingBottom: 10, fontSize: 16, color: colors.text },
  send: { width: 38, height: 38, borderRadius: 19, backgroundColor: colors.primary, alignItems: 'center', justifyContent: 'center' },
});
